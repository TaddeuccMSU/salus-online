/**
 * make-sw.mjs — writes dist/sw.js, the offline service worker for the GitHub
 * Pages build. Run by `npm run build:pages` after `vite build`.
 *
 * What the worker does (plain JavaScript, no libraries):
 *   - On install it downloads EVERY file of the build (app code, styles,
 *     fonts, mock results JSON, report logo, icons) into a cache named after a
 *     hash of the build, so a new build replaces the old copy cleanly.
 *   - Page loads: try the network (4 s limit) and fall back to the saved
 *     index.html, so the app opens offline and any route works.
 *   - App files: served from the saved copy (they are hashed, so never stale).
 *   - Esri map tiles: each tile the person has viewed is kept (newest 3,000),
 *     so fields already looked at still show offline. New areas need a
 *     connection; address search (Nominatim) always does.
 * Note: Esri's terms limit offline use of its basemaps. Fine for internal
 * testing; review before a public release.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const DIST = 'dist';
const SKIP = new Set(['sw.js', '.nojekyll', '404.html', 'pages.tar.gz']);

/** Every file in dist/, as paths relative to the site root. */
function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [relative(DIST, p).split('\\').join('/')];
  });
}
const files = walk(DIST).filter((f) => !SKIP.has(f)).sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);

const sw = `// sw.js — generated by scripts/make-sw.mjs. Do not edit.
const VERSION = '${version}';
const APP = 'salus-app-' + VERSION;
const TILES = 'salus-tiles-v1';
const MAX_TILES = 3000;
const FILES = ${JSON.stringify(['./', ...files], null, 0)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(APP).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('salus-app-') && k !== APP).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

/** Keep the tile cache from growing forever (drops the oldest entries). */
async function trimTiles() {
  const c = await caches.open(TILES);
  const keys = await c.keys();
  for (let i = 0; i < keys.length - MAX_TILES; i++) await c.delete(keys[i]);
}

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);

  // Page loads: network first (4 s), else the saved app shell.
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      try {
        const net = await Promise.race([fetch(req), new Promise((_, no) => setTimeout(() => no(new Error('slow')), 4000))]);
        if (net.ok) return net;
        throw new Error('bad');
      } catch {
        const c = await caches.open(APP);
        return (await c.match('./')) || (await c.match('index.html')) || Response.error();
      }
    })());
    return;
  }

  // Map tiles from Esri: saved copy first, refreshed in the background when online.
  if (url.hostname === 'server.arcgisonline.com') {
    e.respondWith((async () => {
      const c = await caches.open(TILES);
      const hit = await c.match(req);
      const net = fetch(req).then((r) => {
        if (r.ok) c.put(req, r.clone()).then(trimTiles);
        return r;
      }).catch(() => null);
      return hit || (await net) || Response.error();
    })());
    return;
  }

  // The app's own files: saved copy first.
  if (url.origin === self.location.origin) {
    e.respondWith(caches.open(APP).then((c) => c.match(req, { ignoreSearch: true })).then((hit) => hit || fetch(req)));
  }
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`dist/sw.js written: ${files.length} files precached, version ${version}`);
